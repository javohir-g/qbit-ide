#!/usr/bin/env node
/* Writes ide/mpy/qbit_spec.py (the contract table the board's `qbit` module uses) from ide/js/runtime/spec.js,
   so the simulator and the board cannot disagree about names:   node ide/tools/gen_qbit_spec.js [--check] */
'use strict';
const fs = require('fs'), path = require('path'), vm = require('vm');
globalThis.QBIT = globalThis.QBIT || {};
vm.runInThisContext(fs.readFileSync(path.join(__dirname, '..', 'js', 'runtime', 'spec.js'), 'utf8'), { filename: 'spec.js' });
const SPEC = QBIT.SPEC;

const py = (v) => v === undefined || v === null ? 'None' : typeof v === 'string' ? JSON.stringify(v) : String(v);
let out = '# Generated by ide/tools/gen_qbit_spec.js from ide/js/runtime/spec.js: do not edit by hand.\n'
  + '# MODULES[key] = {"values": {python_name: (firmware_name, type)}, "commands": (names...), "events": {name: (kind, value, text, arg)}, "title": ...}\n\n';

function mod(spec) {
  const vals = spec.values.map((v) => '        ' + py(v.py) + ': (' + py(v.n) + ', ' + py(v.t) + '),').join('\n');
  const cmds = spec.commands.map((c) => py(c.n)).join(', ');
  const evs = spec.events.map((e) => '        ' + py(e.n) + ': (' + py(e.kind) + ', ' + py(e.value) + ', ' + py(e.text) + ', ' + py(e.arg) + '),').join('\n');
  return '{\n    "title": ' + py(spec.title || 'плата') + ',\n    "values": {\n' + vals + '\n    },\n    "commands": (' + cmds + (spec.commands.length === 1 ? ',' : '') + '),\n    "events": {\n' + evs + '\n    },\n}';
}
out += 'MODULES = {\n';
SPEC.keys.forEach((k) => { out += '    ' + py(k) + ': ' + mod(SPEC.modules[k]).replace(/\n/g, '\n    ') + ',\n'; });
out += '}\n\nBOARD = ' + mod(SPEC.board) + '\n';
out += '\n# values that mean "everything is off" when a program ends or is stopped: key -> command\nSAFE = {"led": "off", "rgb": "off", "buzzer": "off", "motor": "stop", "relay": "off"}\n';

const file = path.join(__dirname, '..', 'mpy', 'qbit_spec.py');
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
  if (cur !== out) { console.error('mpy/qbit_spec.py is out of date: run node ide/tools/gen_qbit_spec.js'); process.exit(1); }
  console.log('mpy/qbit_spec.py is up to date');
} else {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, out, 'utf8');
  console.log('wrote ' + file + ' (' + out.length + ' bytes)');
}
