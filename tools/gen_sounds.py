#!/usr/bin/env python
"""Blockly's editing sounds as data: URLs:   python -X utf8 ide/tools/gen_sounds.py

    vendor/blockly/media/{click,disconnect,delete,drop}.mp3  ->  js/ide/sounds.js

Blockly fetch()es its sounds from media/, and a page opened straight from a file (file://) may not fetch,
so the editor takes them from js/ide/sounds.js instead. Run again after a Blockly update.
"""
import base64
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MEDIA = ROOT / 'vendor' / 'blockly' / 'media'
NAMES = ('click', 'disconnect', 'delete', 'drop')

lines = ['/* Generated by tools/gen_sounds.py from vendor/blockly/media/*.mp3 (Blockly, Apache-2.0): do not edit.',
         '   The editor gives these to Blockly instead of media/*.mp3, so the sounds work from file:// too. */',
         '(function (G) {',
         '  var Q = G.QBIT = G.QBIT || {};',
         '  Q.BLOCKLY_SOUNDS = {']
for i, name in enumerate(NAMES):
    b64 = base64.b64encode((MEDIA / (name + '.mp3')).read_bytes()).decode('ascii')
    lines.append("    %s: 'data:audio/mpeg;base64,%s'%s" % (name, b64, ',' if i < len(NAMES) - 1 else ''))
lines += ['  };', "})(typeof globalThis !== 'undefined' ? globalThis : this);", '']
out = ROOT / 'js' / 'ide' / 'sounds.js'
out.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
print('%s  %d KB' % (out.relative_to(ROOT), out.stat().st_size // 1024))
