#!/usr/bin/env python
"""Offline / install support:   python -X utf8 ide/tools/gen_pwa.py

  img/icon-192.png, icon-512.png, icon-maskable-512.png, apple-touch-icon.png   from img/qbit-robot.png (blue robot on white)
  img/og.png                                                                   the picture a shared link shows (docs/ide-screenshot.png)
  sw.js                                                                         service worker: every file the page loads is cached on the first visit,
                                                                                the page then opens without a network; online, the network wins (updates arrive at once)

Run it after any change of the files the page loads; tests/pwa.test.js fails when sw.js is out of date."""
import hashlib
import re
import shutil
import sys
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
IMG = ROOT / 'img'


def icon(size: int, pad: float, name: str):
    robot = Image.open(IMG / 'qbit-robot.png').convert('RGBA')
    k = size * (1 - 2 * pad) / max(robot.size)
    r = robot.resize((round(robot.width * k), round(robot.height * k)), Image.LANCZOS)
    bg = Image.new('RGBA', (size, size), (255, 255, 255, 255))
    bg.alpha_composite(r, ((size - r.width) // 2, (size - r.height) // 2))
    bg.convert('RGB').save(IMG / name, optimize=True)


def precache_list():
    html = (ROOT / 'index.html').read_text(encoding='utf-8')
    files = ['./']
    files += re.findall(r'<script src="([^"]+)"', html)
    files += re.findall(r'<link rel="stylesheet" href="([^"]+)"', html)
    files += re.findall(r'<img [^>]*src="([^"]+)"', html)
    files += ['manifest.webmanifest', 'img/icon-192.png', 'img/icon-512.png', 'img/qbit-robot.png',
              'vendor/fonts/montserrat-cyrillic-wght-normal.woff2', 'vendor/fonts/montserrat-latin-wght-normal.woff2',
              'vendor/blockly/media/sprites.svg', 'vendor/blockly/media/delete-icon.svg', 'vendor/blockly/media/dropdown-arrow.svg',
              'vendor/blockly/media/foldout-icon.svg', 'vendor/blockly/media/resize-handle.svg']
    seen, out = set(), []
    for f in files:
        if f not in seen:
            seen.add(f); out.append(f)
    for f in out:
        if f != './' and not (ROOT / f).exists():
            sys.exit('gen_pwa: %s is listed but missing' % f)
    return out


SW = '''/* GENERATED by tools/gen_pwa.py - do not edit by hand.
   Every file of the page is cached on the first visit; later the page opens offline. Online the network is asked first, so a new version
   reaches the user at once, and the cached copy is only the fallback. */
'use strict';
const CACHE = 'qbit-ide-%(version)s';
const FILES = %(files)s;

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE && k.indexOf('qbit-ide-') === 0).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  const req = e.request, url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== location.origin) return;
  if (url.pathname.endsWith('/qbit.json')) return;                       // the board probe: never from the cache
  e.respondWith(fetch(req).then((res) => {
    if (res && res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }
    return res;
  }).catch(() => caches.match(req, { ignoreSearch: true }).then((hit) => hit || (req.mode === 'navigate' ? caches.match('./') : Response.error()))));
});
'''


def main():
    icon(192, 0.12, 'icon-192.png')
    icon(512, 0.12, 'icon-512.png')
    icon(512, 0.26, 'icon-maskable-512.png')          # the platform crops a circle or a rounded square out of the middle
    icon(180, 0.12, 'apple-touch-icon.png')
    shutil.copyfile(ROOT / 'docs' / 'ide-screenshot.png', IMG / 'og.png')
    files = precache_list()
    h = hashlib.sha1()
    for f in files:
        p = ROOT / ('index.html' if f == './' else f)
        h.update(f.encode()); h.update(p.read_bytes())
    sw = SW % {'version': h.hexdigest()[:10], 'files': '[\n  ' + ',\n  '.join("'%s'" % f for f in files) + '\n]'}
    (ROOT / 'sw.js').write_text(sw, encoding='utf-8', newline='\n')
    print('sw.js: %d files, version %s' % (len(files), h.hexdigest()[:10]))


main()
