  var cols = {};
  function columns(ch) {
    var c = cols[ch];
    if (c) return c;
    var r = rows[ch] || rows['?'];
    c = new Uint8Array(5);
    for (var x = 0; x < 5; x++) {
      var b = 0;
      for (var y = 0; y < 7; y++) if (r[y][x] === '#') b |= 1 << y;
      c[x] = b;
    }
    cols[ch] = c;
    return c;
  }

  Q.font5x7 = {
    width: 5, height: 7, advance: 6, lineHeight: 8,
    has: function (ch) { return !!rows[ch]; },
    columns: columns,
    /** pixel width of a string at `size` (no trailing gap) */
    measure: function (str, size) { size = size || 1; return str.length ? (str.length * 6 - 1) * size : 0; },
    /** draw into a W x H 0/1 framebuffer */
    draw: function (fb, W, H, str, x, y, size, on) {
      size = size || 1;
      var cx = x, cy = y;
      for (var i = 0; i < str.length; i++) {
        var ch = str[i];
        if (ch === '\n') { cx = x; cy += 8 * size; continue; }
        var c = columns(ch);
        for (var col = 0; col < 5; col++) {
          for (var row = 0; row < 7; row++) {
            if (!(c[col] & (1 << row))) continue;
            for (var sx = 0; sx < size; sx++) for (var sy = 0; sy < size; sy++) {
              var px = cx + col * size + sx, py = cy + row * size + sy;
              if (px >= 0 && px < W && py >= 0 && py < H) fb[py * W + px] = on === 0 ? 0 : 1;
            }
          }
        }
        cx += 6 * size;
      }
    },
    glyphs: function () { return Object.keys(rows); }
  };
